function u_signal = project2_func6(time_instant, series_id, split_name)
    if strcmp(split_name, 'train')
        u_signal = 0.5 * sin((0.35 + 0.04 * series_id) * time_instant + 0.2 * series_id) + ...
                   0.35 * cos((0.95 + 0.03 * series_id) * time_instant) + ...
                   0.2 * sin((1.7 + 0.02 * series_id) * time_instant + 0.5 * series_id);
    else
        u_signal = 0.45 * sin((0.5 + 0.05 * series_id) * time_instant + 0.6 * series_id) + ...
                   0.3 * cos((1.35 + 0.04 * series_id) * time_instant + 0.4) + ...
                   0.18 * sign(sin(0.75 * time_instant + series_id));
    end
end